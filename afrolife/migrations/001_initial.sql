CREATE OR REPLACE FUNCTION check_match_worker_verified() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM workers w
    WHERE w.id = NEW.worker_id AND w.verification = 'verified'
      AND EXISTS (SELECT 1 FROM documents d WHERE d.worker_id = w.id AND d.doc_type = 'national_id' AND d.status = 'verified' AND (d.expires_on IS NULL OR d.expires_on > current_date))
      AND EXISTS (SELECT 1 FROM documents d WHERE d.worker_id = w.id AND d.doc_type = 'police_clearance' AND d.status = 'verified' AND (d.expires_on IS NULL OR d.expires_on > current_date))
  ) THEN
    RAISE EXCEPTION 'Worker is not verified';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER matches_require_verified_worker BEFORE INSERT ON matches
FOR EACH ROW EXECUTE FUNCTION check_match_worker_verified();

