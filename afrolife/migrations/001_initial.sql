CREATE TABLE ledger_entries (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  txn_id uuid NOT NULL,
  account text NOT NULL,
  debit numeric(14,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
  credit numeric(14,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
  ref_type text NOT NULL,
  ref_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0))
);
CREATE INDEX ledger_entries_ref_idx ON ledger_entries (ref_type, ref_id);

CREATE OR REPLACE FUNCTION assert_ledger_txn_balanced() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE txn uuid;
DECLARE total_debit numeric(14,2);
DECLARE total_credit numeric(14,2);
BEGIN
  txn := NEW.txn_id;
  SELECT coalesce(sum(debit),0), coalesce(sum(credit),0)
    INTO total_debit, total_credit
    FROM ledger_entries WHERE txn_id = txn;
  IF total_debit <> total_credit THEN
    RAISE EXCEPTION 'Ledger transaction % is unbalanced: debit %, credit %', txn, total_debit, total_credit;
  END IF;
  RETURN NULL;
END
$$;
CREATE CONSTRAINT TRIGGER ledger_txn_balanced
AFTER INSERT ON ledger_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_ledger_txn_balanced();

