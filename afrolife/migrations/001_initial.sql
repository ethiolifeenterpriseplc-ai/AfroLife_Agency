CREATE OR REPLACE FUNCTION prevent_unverified_activation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.active AND NEW.role NOT IN ('super_admin','compliance','finance','finance_manager')
     AND NEW.kyc_status <> 'verified' THEN
    RAISE EXCEPTION 'Account must be KYC verified before activation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER users_require_kyc_before_activation
BEFORE INSERT OR UPDATE OF active, role, kyc_status ON users
FOR EACH ROW EXECUTE FUNCTION prevent_unverified_activation();

